import { describe, it, expect, beforeEach, afterEach } from "vitest";
import { prisma } from "@/lib/db";
import { upsertItems } from "@/lib/ingest/ingest";
import { runAgent } from "@/lib/agent/agent";
import { saveAgentSettings } from "@/lib/agent/settings";
import { setAIProviderForTests, type AIProvider, type SourceMaterial, type StorySuggestion } from "@/lib/ai/provider";
import { setEmailProviderForTests, type EmailProvider, type OutgoingEmail } from "@/lib/email/provider";
import { resetDb, makeSource } from "../helpers";

class FakeAI implements AIProvider {
  name = "fake";
  enabled = true;
  calls = 0;
  /** When true, the draft invents a CVE that is not in the source. */
  hallucinate = false;
  fail = false;
  async suggestStory(sources: SourceMaterial[]): Promise<StorySuggestion> {
    this.calls++;
    if (this.fail) throw new Error("rate limited");
    const t = sources[0].title;
    return {
      headline: `Advisory: ${t}`.slice(0, 110),
      summary: `${sources[0].sourceName} disclosed an issue: ${t}. Updates are listed in the advisory.${this.hallucinate ? " See also CVE-2026-424242." : ""}`,
      whyItMatters: "Controllers like these run physical processes.",
      defensiveGuidance: "",
      guidanceSource: "",
      categories: ["vendor-advisories"],
      vendors: ["Siemens", "InventedVendor"],
      products: [],
      unknowns: ["exploitation status"],
    };
  }
}

class FakeMail implements EmailProvider {
  name = "fake";
  sendsRealEmail = true;
  sent: OutgoingEmail[] = [];
  async send(m: OutgoingEmail) {
    this.sent.push(m);
    return { accepted: true, providerMessageId: `m${this.sent.length}` };
  }
}

let ai: FakeAI;
let mail: FakeMail;
const NOW = new Date("2026-11-02T08:00:00Z"); // Monday, after the default 07:00 UTC send slot
const recent = new Date("2026-10-30T10:00:00Z");

async function seedItems() {
  const vendor = await makeSource({ trustLevel: "primary_vendor", category: "vendor-advisories", name: "Siemens ProductCERT" });
  const news = await makeSource({ trustLevel: "news", category: "security-news", name: "Some News" });
  const base = { author: null, sourceUpdatedAt: null, publishedAt: recent };
  await upsertItems(vendor, [
    { ...base, guid: "a", url: "https://vendor.example/ssa-111111", title: "SSA-111111: Denial of Service in Siemens SIMATIC S7-1500 PLC", excerpt: "Siemens SIMATIC S7-1500 PLC is affected by CVE-2026-11111. Update firmware." },
    { ...base, guid: "b", url: "https://vendor.example/ssa-222222", title: "SSA-222222: Authentication bypass in Siemens SCADA HMI WinCC", excerpt: "WinCC HMI authentication bypass, CVE-2026-22222." },
    { ...base, guid: "c", url: "https://vendor.example/old", title: "SSA-333333: Old Siemens PLC advisory", excerpt: "PLC", publishedAt: new Date("2026-09-01T00:00:00Z") },
    { ...base, guid: "d", url: "https://vendor.example/office", title: "Office printer driver update", excerpt: "Generic IT item without industrial terms." },
  ], NOW);
  await upsertItems(news, [
    { ...base, guid: "n", url: "https://news.example/plc", title: "Siemens PLC flaw CVE-2026-11111 explained", excerpt: "News coverage of SIMATIC PLC issue." },
  ], NOW);
}

beforeEach(async () => {
  await resetDb();
  ai = new FakeAI();
  mail = new FakeMail();
  setAIProviderForTests(ai);
  setEmailProviderForTests(mail);
  delete process.env.AGENT_DISABLED;
});
afterEach(() => {
  setAIProviderForTests(null);
  setEmailProviderForTests(null);
});

describe("news agent", () => {
  it("writes and publishes stories only from recent, relevant, primary-source items", async () => {
    await seedItems();
    await saveAgentSettings({ autoSend: false });
    const r = await runAgent({ trigger: "test", now: NOW, skipFetch: true });
    expect(r.status).toBe("ok");
    expect(r.storiesPublished).toBe(2); // SSA-111111 (+ news item with same CVE is not primary) and SSA-222222
    const stories = await prisma.story.findMany({ include: { sources: { include: { item: true } } }, orderBy: { headline: "asc" } });
    expect(stories.every((s) => s.editorialStatus === "published" && s.autoGenerated && s.aiAssisted)).toBe(true);
    expect(stories.every((s) => s.verificationStatus === "partially_verified")).toBe(true);
    // Never invents: vendor not in the source is dropped; CVEs come from the source only.
    expect(stories.flatMap((s) => s.vendors)).not.toContain("InventedVendor");
    expect(stories.map((s) => s.cveIds).flat().sort()).toEqual(["CVE-2026-11111", "CVE-2026-22222"]);
    // Old and non-industrial items are left alone.
    const untouched = await prisma.collectedItem.findMany({ where: { guid: { in: ["c", "d"] } } });
    expect(untouched.every((i) => i.inboxStatus !== "used")).toBe(true);
    const runs = await prisma.agentRun.findMany();
    expect(runs).toHaveLength(1);
    expect(runs[0].storiesPublished).toBe(2);
  });

  it("falls back to the publisher's wording when the AI invents facts or fails", async () => {
    await seedItems();
    await saveAgentSettings({ autoSend: false, maxStoriesPerRun: 1 });
    ai.hallucinate = true;
    const r = await runAgent({ trigger: "test", now: NOW, skipFetch: true });
    expect(r.storiesPublished).toBe(1);
    expect(r.log.some((l) => l.level === "warn" && /CVE-2026-424242/.test(l.msg))).toBe(true);
    const s = await prisma.story.findFirstOrThrow();
    expect(s.summary).not.toContain("424242");
    expect(s.summary).toMatch(/^Siemens ProductCERT reports:/);
    expect(s.aiAssisted).toBe(false);

    ai.hallucinate = false;
    ai.fail = true;
    const r2 = await runAgent({ trigger: "test", now: NOW, skipFetch: true });
    expect(r2.storiesPublished).toBe(1);
    expect(r2.log.some((l) => /rate limited/.test(l.msg))).toBe(true);
  });

  it("does not duplicate: a second run links new sources to the existing story", async () => {
    await seedItems();
    await saveAgentSettings({ autoSend: false, trustLevels: ["primary_vendor", "news"] });
    await runAgent({ trigger: "test", now: NOW, skipFetch: true });
    const count = await prisma.story.count();
    const vendor = await prisma.source.findFirstOrThrow({ where: { trustLevel: "primary_vendor" } });
    // A later update about the same CVE from the same vendor.
    await upsertItems(vendor, [
      { guid: "a2", url: "https://vendor.example/ssa-111111-v2", title: "SSA-111111 V1.1: Siemens SIMATIC PLC update", excerpt: "CVE-2026-11111 fix extended.", author: null, publishedAt: recent, sourceUpdatedAt: null },
    ], NOW);
    const r = await runAgent({ trigger: "test", now: NOW, skipFetch: true });
    expect(await prisma.story.count()).toBe(count);
    expect(r.itemsLinked).toBeGreaterThanOrEqual(1);
    const ssa = await prisma.story.findFirstOrThrow({ where: { cveIds: { has: "CVE-2026-11111" } }, include: { _count: { select: { sources: true } } } });
    expect(ssa._count.sources).toBeGreaterThanOrEqual(2);
  });

  it("sends the weekly issue once per slot, only to active subscribers", async () => {
    await seedItems();
    await prisma.subscriber.create({ data: { email: "reader@example.com", status: "active", consentAt: NOW, consentTextVersion: "t", unsubscribeTokenHash: "h1" } });
    await prisma.subscriber.create({ data: { email: "pending@example.com", status: "pending", consentAt: NOW, consentTextVersion: "t", unsubscribeTokenHash: "h2" } });
    const r = await runAgent({ trigger: "test", now: NOW, skipFetch: true });
    expect(r.issueId).toBeTruthy();
    const issue = await prisma.newsletterIssue.findUniqueOrThrow({ where: { id: r.issueId! }, include: { _count: { select: { stories: true } } } });
    expect(issue.status).toBe("sending");
    expect(issue._count.stories).toBe(2);
    const { processSending } = await import("@/lib/newsletter/send");
    await processSending();
    expect(mail.sent.map((m) => m.to)).toEqual(["reader@example.com"]);
    expect(mail.sent[0].html).toContain("Auto-generated, not editor-reviewed");
    // Same slot again: no second issue.
    const r2 = await runAgent({ trigger: "test", now: new Date(NOW.getTime() + 3600_000), skipFetch: true });
    expect(r2.issueId).toBeNull();
    expect(await prisma.newsletterIssue.count()).toBe(1);
  });

  it("skips the weekly send when there are no new stories", async () => {
    const r = await runAgent({ trigger: "test", now: NOW, skipFetch: true });
    expect(r.issueId).toBeNull();
    expect(r.log.some((l) => /Weekly issue skipped/.test(l.msg))).toBe(true);
  });

  it("dry run writes and sends nothing", async () => {
    await seedItems();
    const r = await runAgent({ trigger: "manual", dryRun: true, now: NOW, skipFetch: true });
    expect(r.candidates).toBeGreaterThan(0);
    expect(r.log.some((l) => /^Would write/.test(l.msg))).toBe(true);
    expect(await prisma.story.count()).toBe(0);
    expect(await prisma.newsletterIssue.count()).toBe(0);
    expect(ai.calls).toBe(0);
  });

  it("respects the off switch and the AGENT_DISABLED kill switch", async () => {
    await seedItems();
    await saveAgentSettings({ enabled: false });
    expect((await runAgent({ trigger: "schedule", now: NOW, skipFetch: true })).status).toBe("skipped");
    await saveAgentSettings({ enabled: true });
    process.env.AGENT_DISABLED = "1";
    expect((await runAgent({ trigger: "manual", now: NOW, skipFetch: true })).status).toBe("skipped");
    expect(await prisma.story.count()).toBe(0);
  });

  it("merges the same advisory from a vendor and a CERT even without shared IDs", async () => {
    const vendor = await makeSource({ trustLevel: "primary_vendor", name: "Siemens ProductCERT" });
    const cert = await makeSource({ trustLevel: "government_cert", name: "CISA ICS Advisories" });
    const text = "Mendix SAML module contains an authentication bypass vulnerability that could allow an unauthenticated remote attacker to gain unauthorized access to the Siemens application.";
    await upsertItems(vendor, [{ guid: "s", url: "https://vendor.example/ssa-137528", title: "SSA-137528 V1.0: Authentication Bypass Vulnerability in Mendix SAML module", excerpt: text, author: null, publishedAt: recent, sourceUpdatedAt: null }], NOW);
    await upsertItems(cert, [{ guid: "c", url: "https://cisa.example/icsa-26-302-01", title: "Siemens Mendix SAML Module", excerpt: `${text} CVE-2026-89209.`, author: null, publishedAt: recent, sourceUpdatedAt: null }], NOW);
    await saveAgentSettings({ autoSend: false });
    const r = await runAgent({ trigger: "test", now: NOW, skipFetch: true });
    expect(r.storiesPublished).toBe(1);
    const s = await prisma.story.findFirstOrThrow({ include: { _count: { select: { sources: true } } } });
    expect(s._count.sources).toBe(2);
  });

  it("drafts only when auto-publish is off", async () => {
    await seedItems();
    await saveAgentSettings({ autoPublish: false, autoSend: false });
    const r = await runAgent({ trigger: "test", now: NOW, skipFetch: true });
    expect(r.storiesCreated).toBe(2);
    expect(r.storiesPublished).toBe(0);
    expect(await prisma.story.count({ where: { editorialStatus: "draft" } })).toBe(2);
  });
});
