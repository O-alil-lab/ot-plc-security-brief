import type { Metadata } from "next";
import Link from "next/link";
import { prisma } from "@/lib/db";
import { requireAdminPage } from "@/lib/auth/session";
import { getAIProvider } from "@/lib/ai/provider";
import { getEmailProvider } from "@/lib/email/provider";
import { getAgentSettings, agentDisabledByEnv, TRUST_LABEL } from "@/lib/agent/settings";
import { currentSendSlot, type AgentLogEntry } from "@/lib/agent/agent";
import { Flash, type FlashParams } from "@/components/admin/Flash";
import { Csrf } from "@/components/admin/Csrf";
import { PageTitle, Empty, fmtDateTime, ago } from "@/components/admin/ui";
import { saveAgentSettingsAction, runAgentAction } from "../../actions";

export const metadata: Metadata = { title: "News agent" };

const DAYS = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"];

export default async function AgentPage({ searchParams }: { searchParams: FlashParams }) {
  await requireAdminPage();
  const sp = await searchParams;
  const [settings, runs, autoCount, activeSubs] = await Promise.all([
    getAgentSettings(),
    prisma.agentRun.findMany({ orderBy: { startedAt: "desc" }, take: 15 }),
    prisma.story.count({ where: { autoGenerated: true, editorialStatus: "published" } }),
    prisma.subscriber.count({ where: { status: "active" } }),
  ]);
  const ai = getAIProvider();
  const mail = getEmailProvider();
  const envOff = agentDisabledByEnv();
  const nextSlot = new Date(currentSendSlot(new Date(), settings.sendWeekday, settings.sendHourUtc).getTime() + 7 * 86_400_000);

  const status = envOff || !settings.enabled ? "Off" : settings.autoPublish && settings.autoSend ? "Fully automatic" : settings.autoPublish ? "Publishes stories; you send the newsletter" : "Drafts only";

  return (
    <>
      <Flash msg={sp.msg} error={sp.error} />
      <PageTitle title="News agent">
        <form action={runAgentAction}>
          <Csrf />
          <input type="hidden" name="dryRun" value="yes" />
          <button className="btn btn-secondary">Dry run (preview)</button>
        </form>
        <form action={runAgentAction}>
          <Csrf />
          <button className="btn btn-primary">Run now</button>
        </form>
      </PageTitle>
      <p className="-mt-3 mb-6 max-w-[72ch] text-sm text-slate">
        Every hour the agent fetches the newest items from your sources, picks relevant industrial advisories from the source types you allow, writes a story for each topic, and{" "}
        {settings.autoPublish ? "publishes it" : "leaves it as a draft"}. {settings.autoSend ? "Once a week it sends the newsletter with the week's published stories." : ""} It never invents facts: AI text is checked against the source and anything unsupported is removed or replaced with the publisher&apos;s own wording.
      </p>

      <dl className="mb-8 grid gap-3 text-sm sm:grid-cols-2 xl:grid-cols-4">
        <div className="rounded-md border border-line p-3">
          <dt className="font-medium">Mode</dt>
          <dd className={status === "Off" ? "text-danger" : "text-slate"}>{status}{envOff && " (AGENT_DISABLED is set)"}</dd>
        </div>
        <div className="rounded-md border border-line p-3">
          <dt className="font-medium">Writing</dt>
          <dd className="text-slate">{ai.enabled ? `AI (${ai.name}), checked against the source` : "Publisher's wording (set ANTHROPIC_API_KEY to enable AI)"}</dd>
        </div>
        <div className="rounded-md border border-line p-3">
          <dt className="font-medium">Next weekly send</dt>
          <dd className="text-slate">{settings.autoSend ? `${fmtDateTime(nextSlot)} to ${activeSubs} active subscriber${activeSubs === 1 ? "" : "s"}` : "Manual"}</dd>
        </div>
        <div className="rounded-md border border-line p-3">
          <dt className="font-medium">Email</dt>
          <dd className="text-slate">{mail.sendsRealEmail ? `${mail.name} (real email)` : "Development mode: goes to the Dev mailbox only"}</dd>
        </div>
      </dl>

      <div className="grid gap-10 xl:grid-cols-[1fr_24rem]">
        <section aria-labelledby="runs">
          <h2 id="runs" className="mb-3 text-lg font-semibold">Recent runs</h2>
          {runs.length === 0 ? (
            <Empty title="No runs yet.">The worker runs the agent every hour, or press “Run now”.</Empty>
          ) : (
            <ul className="space-y-3">
              {runs.map((r) => {
                const log = (r.log ?? []) as AgentLogEntry[];
                return (
                  <li key={r.id} className="rounded-lg border border-line p-4 text-sm">
                    <details>
                      <summary className="cursor-pointer">
                        <strong className={r.status === "failed" ? "text-danger" : ""}>{r.dryRun ? "Dry run" : r.status === "ok" ? "Run" : r.status === "running" ? "Running" : "Failed run"}</strong>{" "}
                        <span className="text-slate">
                          {ago(r.startedAt)} ({r.trigger}) — {r.storiesPublished} published, {r.storiesCreated} written, {r.itemsLinked} linked, {r.candidates} topics
                          {r.issueId ? " — weekly issue queued" : ""}
                        </span>
                      </summary>
                      <ul className="mt-2 space-y-1">
                        {log.map((l, i) => (
                          <li key={i} className={l.level === "warn" ? "text-lamp-amber" : "text-slate"}>
                            {l.msg}
                          </li>
                        ))}
                        {r.error && <li className="text-danger">{r.error}</li>}
                      </ul>
                      {r.issueId && <Link href={`/admin/newsletter/${r.issueId}`} className="mt-2 inline-block">Open the issue</Link>}
                    </details>
                  </li>
                );
              })}
            </ul>
          )}
          <p className="mt-4 text-sm text-slate">
            {autoCount} auto-generated stor{autoCount === 1 ? "y is" : "ies are"} live. <Link href="/admin/stories?status=published">Review published stories</Link>; you can edit or unpublish any of them.
          </p>
        </section>

        <form action={saveAgentSettingsAction} className="space-y-4 text-sm">
          <Csrf />
          <h2 className="text-lg font-semibold">Settings</h2>
          <fieldset className="space-y-2">
            <legend className="sr-only">Switches</legend>
            <label className="flex items-center gap-2"><input type="checkbox" name="enabled" defaultChecked={settings.enabled} className="accent-teal" /> Agent switched on</label>
            <label className="flex items-center gap-2"><input type="checkbox" name="autoPublish" defaultChecked={settings.autoPublish} className="accent-teal" /> Publish stories automatically</label>
            <label className="flex items-center gap-2"><input type="checkbox" name="autoSend" defaultChecked={settings.autoSend} className="accent-teal" /> Send the weekly newsletter automatically</label>
          </fieldset>
          <div className="grid grid-cols-2 gap-3">
            <label className="block">
              <span className="mb-1 block font-medium">Send day</span>
              <select name="sendWeekday" defaultValue={settings.sendWeekday} className="field">
                {DAYS.map((d, i) => <option key={d} value={i}>{d}</option>)}
              </select>
            </label>
            <label className="block">
              <span className="mb-1 block font-medium">Send hour (UTC)</span>
              <input name="sendHourUtc" type="number" min={0} max={23} defaultValue={settings.sendHourUtc} className="field" />
            </label>
          </div>
          <fieldset>
            <legend className="mb-1 font-medium">Write stories from</legend>
            {(["primary_vendor", "government_cert", "research", "news"] as const).map((t) => (
              <label key={t} className="flex items-center gap-2">
                <input type="checkbox" name="trustLevels" value={t} defaultChecked={settings.trustLevels.includes(t)} className="accent-teal" />
                {TRUST_LABEL[t]}
                {(t === "research" || t === "news") && <span className="text-xs text-slate">(secondary; less reliable)</span>}
              </label>
            ))}
          </fieldset>
          <div className="grid grid-cols-2 gap-3">
            <label className="block"><span className="mb-1 block font-medium">Minimum relevance</span><input name="minRelevance" type="number" min={0} max={100} defaultValue={settings.minRelevance} className="field" /></label>
            <label className="block"><span className="mb-1 block font-medium">Look back (days)</span><input name="lookbackDays" type="number" min={1} max={30} defaultValue={settings.lookbackDays} className="field" /></label>
            <label className="block"><span className="mb-1 block font-medium">Max stories per run</span><input name="maxStoriesPerRun" type="number" min={1} max={50} defaultValue={settings.maxStoriesPerRun} className="field" /></label>
            <label className="block"><span className="mb-1 block font-medium">Max stories per issue</span><input name="maxStoriesPerIssue" type="number" min={1} max={30} defaultValue={settings.maxStoriesPerIssue} className="field" /></label>
            <label className="block"><span className="mb-1 block font-medium">Min stories to send</span><input name="minStoriesPerIssue" type="number" min={1} max={30} defaultValue={settings.minStoriesPerIssue} className="field" /></label>
          </div>
          <button className="btn btn-primary">Save settings</button>
          <p className="text-xs text-slate">Emergency stop: untick “Agent switched on”, or set AGENT_DISABLED=1 and restart.</p>
        </form>
      </div>
    </>
  );
}
